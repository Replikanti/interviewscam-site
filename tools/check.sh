#!/usr/bin/env bash
# The single local and CI entry point: CI runs `bash tools/check.sh` verbatim.
#
# Every step runs even after an earlier one failed, then a summary prints
# PASS / FAIL / SKIPPED / NOT RUN (CI only) per step, and the exit code is 1
# if any step failed.
#
# The Nu Html Checker (ADR-0002 part 1) and the reflow check (ADR-0003
# part 6) run only in CI (GITHUB_ACTIONS=true). Outside CI each step prints a
# loud NOT RUN line and the final line never uses all-pass wording. In CI a
# missing container runtime, image or Chrome is FAIL.
#
# Usage: bash tools/check.sh [--external]
#   --external  check links online (third-party sites included) instead of
#               the offline internal-link check (ADR-0002 part 7); the
#               fixture build's links stay offline, because its sources
#               and lookups are placeholders
#
# The fixture build (ADR-0004 part 10): production content/ has no records
# until milestone 5, so the record templates would meet no check before
# then. A second build of the real templates on the canonical fixture
# records (tests/fixtures/records/pass-fixture-site/) goes into
# public-fixtures/ and gets the same site, render, reflow, HTML and offline
# link checks. It is assembled in .fixture-site/, never in content/, and the
# deploy artifact stays public/ alone. Its inputs are classified (the
# FIXTURE_* arrays below), so no input of the production build is missing
# from it.
#
# tools/selftest.sh sources this file for html_check, links_check,
# reflow_check and the sitecheck functions, so the self-test runs exactly the invocations the real
# steps run; check_main and the strict mode below apply only when the file is
# executed.

CHECK_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# The fixture build: its source tree, its output and the records it adds.
FIXTURE_SITE="$CHECK_ROOT/.fixture-site"
FIXTURE_PUBLIC="$CHECK_ROOT/public-fixtures"
FIXTURE_RECORDS="$CHECK_ROOT/tests/fixtures/records/pass-fixture-site/content"
# Every top-level entry of the repo root on disk is classified, because Hugo
# reads the disk, not git: an ignored i18n/ or a stray go.mod would change
# the production build and not the fixture build (ADR-0004 part 10,
# amended). fixture_inputs fails on an entry in no array or in two.
#   FIXTURE_COPY     Hugo site inputs, copied whole into .fixture-site/ when
#                    present
#   FIXTURE_CONTENT  content: its top-level *.md are copied, and the record
#                    sections (FIXTURE_RECORD_SECTIONS) come from the fixture
#                    records; any other entry of content/ (a directory, a
#                    file that is not *.md) fails, because the fixture build
#                    would silently lack it
#   FIXTURE_SKIP     not read by the Hugo build, or generated by it or by
#                    this script
FIXTURE_COPY=(hugo.toml layouts assets data static i18n archetypes)
FIXTURE_CONTENT=(content)
FIXTURE_RECORD_SECTIONS=(reports campaigns)
FIXTURE_SKIP=(.git .github .gitignore .hugo_build.lock .tools .fixture-site
  public public-fixtures resources worktrees CLAUDE.md README.md docs
  lychee.toml schema tests tools)
# shellcheck source=tools/fetch-tools.sh
source "$CHECK_ROOT/tools/fetch-tools.sh"

HTML_NOT_RUN_LINE='NOT RUN: HTML validation (Nu Html Checker) was NOT run locally. It runs only in CI (required check job). A local green does not mean the HTML is valid.'
REFLOW_NOT_RUN_LINE='NOT RUN: reflow at 320 CSS px (sitecheck reflow) was NOT run locally, and with it its hidden-state cases (the Copy button hidden without its script, the search results hidden until a query, the skip link shown on keyboard focus). It runs only in CI, in the runner'"'"'s Google Chrome. A local green does not mean the pages reflow or hide and reveal as they should.'

in_github_actions() { [[ "${GITHUB_ACTIONS:-}" == true ]]; }

# html_check <absolute dir>: validate every HTML and CSS file under dir with
# the pinned Nu Html Checker image. Only ever called in CI.
html_check() {
  local dir="$1"
  if ! command -v docker >/dev/null 2>&1; then
    echo "FAIL: docker not found; in CI the Nu Html Checker must run" >&2
    return 1
  fi
  if ! docker image inspect "$VNU_IMAGE" >/dev/null 2>&1; then
    echo "FAIL: pinned Nu Html Checker image not present: $VNU_IMAGE" >&2
    echo "FAIL: tools/fetch-tools.sh pulls it in CI; see its output" >&2
    return 1
  fi
  docker run --rm --network none -v "$dir:/site:ro" --entrypoint vnu \
    "$VNU_IMAGE" --skip-non-html --also-check-css /site
}

# links_check <absolute dir> [--external]: check links in the built tree.
# root_dir and the self-link remap depend on the absolute path, so they are
# passed here rather than in lychee.toml.
links_check() {
  local dir="$1" mode="${2:-}"
  local -a online=(--offline)
  [[ "$mode" == --external ]] && online=()
  if [[ ! -x "$LYCHEE_BIN" ]]; then
    echo "FAIL: lychee not found at $LYCHEE_BIN; run tools/fetch-tools.sh" >&2
    return 1
  fi
  "$LYCHEE_BIN" --config "$CHECK_ROOT/lychee.toml" "${online[@]}" \
    --root-dir "$dir" \
    --remap "^https://interviewscam\\.com/(.*)\$ file://$dir/\$1" \
    -- "$dir"
}

# reflow_check <absolute dir>: load every HTML page under dir at 320 CSS px
# in the runner's Google Chrome (ADR-0003 part 6). Only ever called in CI.
reflow_check() {
  local chrome
  chrome="$(command -v google-chrome || command -v google-chrome-stable)" || {
    echo "FAIL: Google Chrome not found; in CI the reflow check must run" >&2
    return 1
  }
  sitecheck reflow --chrome "$chrome" "$1"
}

# The safety nets (tools/sitecheck.py, ADR-0002 parts 3, 4 and 6), run in
# Python's isolated mode. Each prints its counts and exits 1 on findings,
# 2 on a usage or internal error.
sitecheck() { python3 -I "$CHECK_ROOT/tools/sitecheck.py" "$@"; }

# guard_check <repo root>: no JavaScript package tooling in the build chain
# (D3; the guard keeps the tool names out of tools/), Hugo hardening keys in
# hugo.toml and in the effective config of the pinned Hugo, actions owned by
# actions/ and pinned to commit SHAs, Pages off until M6.
guard_check() { sitecheck guard --root "$1" --hugo "$HUGO_BIN"; }

# records_check <root> <schema dir>: schema, x-defang (D8), live forms (R2),
# the SPEC section 5 body rule and the record rules R4 to R15 (ADR-0004) for
# every record and _index.md under <root>/content.
records_check() { sitecheck records --root "$1" --schemas "$2"; }

# site_check <root> <schema dir> <built dir> [no-built-pins]: third-party
# requests (D9), the CSP meta from <root>/hugo.toml, no live artifact in the
# build (R3), and the built stylesheet and scripts against their pins; the
# fourth argument turns those pins off, for the self-test's hand-made site
# fixtures only (the check steps never pass it, wiring/site-built-pins).
site_check() {
  local pins=()
  [[ "${4:-}" == no-built-pins ]] && pins=(--no-built-pins)
  sitecheck site --records "$1" --schemas "$2" "${pins[@]}" "$3"
}

# render_check <root> <schema dir> <built dir> [<fixtures dir>] [no-feed]
# [no-search]: the markup contract of the record pages (ADR-0004): one page
# per record and none without one, the fixed titles, the D6, D7 and D10
# wording, the campaign line and attribution, artifacts and external links,
# structured data, no hidden persona name anywhere, the index lists, the
# data feed /feed.json against its schema, the records and /data-feed/
# (rules 11 to 13), and the A to Z page /a-z/ with the Home search form
# (rule 15, ADR-0005). With a fixtures dir, no record may share its slug or
# name with a fixture record under <fixtures dir>/**/content/ (the
# fixture-leak check; production only). no-feed and no-search (the
# self-test's render fixtures only) leave out rules 11 to 13 and rule 15;
# both builds always run them.
render_check() {
  local fixtures=() feed=() search=()
  [[ -n "${4:-}" ]] && fixtures=(--fixtures "$4")
  [[ "${5:-}" == no-feed ]] && feed=(--no-feed)
  [[ "${6:-}" == no-search ]] && search=(--no-search)
  sitecheck render --records "$1" --schemas "$2" "${fixtures[@]}" "${feed[@]}" \
    "${search[@]}" "$3"
}

# literals_check <root>: fixed public copy only from data/labels.toml
# (ADR-0004 part 13): no copy in template text, visible attributes, action
# literals or CSS generated text, and copy read only through label.html and
# label-list.html, under <root>/layouts, <root>/assets and <root>/static.
literals_check() { sitecheck literals --root "$1"; }

# tokens_check <root>: data/tokens.toml well formed, every listed colour pair
# at its WCAG 2.2 contrast minimum, and no colour literal in the site sources
# (SPEC section 7).
tokens_check() { sitecheck tokens --root "$1"; }

STEP_NAMES=()
STEP_RESULTS=()

record() {
  STEP_NAMES+=("$1")
  STEP_RESULTS+=("$2")
}

# run_step <name> <command...>: run, record PASS or FAIL, never abort.
run_step() {
  local name="$1"
  shift
  echo
  echo "==> $name"
  if "$@"; then
    record "$name" PASS
  else
    echo "==> $name: FAIL"
    record "$name" FAIL
  fi
}

step_fetch() { bash "$CHECK_ROOT/tools/fetch-tools.sh"; }

step_shellcheck() {
  if ! command -v shellcheck >/dev/null 2>&1; then
    if [[ "${CI:-}" == true ]]; then
      echo "shellcheck not found; in CI it is required" >&2
      return 1
    fi
    echo "SKIPPED: shellcheck not found, shell scripts were NOT linted"
    return 2
  fi
  shellcheck --version | sed -n 's/^version: /shellcheck version: /p'
  shellcheck -x "$CHECK_ROOT"/tools/*.sh || return 1
  echo "shellcheck OK"
}

step_guard() { guard_check "$CHECK_ROOT"; }

step_records() { records_check "$CHECK_ROOT" "$CHECK_ROOT/schema"; }

step_tokens() { tokens_check "$CHECK_ROOT"; }

step_literals() { literals_check "$CHECK_ROOT"; }

step_site() { site_check "$CHECK_ROOT" "$CHECK_ROOT/schema" "$CHECK_ROOT/public"; }

step_site_fixtures() { site_check "$FIXTURE_SITE" "$CHECK_ROOT/schema" "$FIXTURE_PUBLIC"; }

step_render() {
  render_check "$CHECK_ROOT" "$CHECK_ROOT/schema" "$CHECK_ROOT/public" \
    "$CHECK_ROOT/tests/fixtures"
}

# The fixture tree is not the production tree, so it never gets the
# fixture-leak check (--fixtures): every record in it is a fixture.
step_render_fixtures() {
  render_check "$FIXTURE_SITE" "$CHECK_ROOT/schema" "$FIXTURE_PUBLIC"
}

# hugo_build <source dir> <destination dir>: the one Hugo invocation, for
# the production build and the fixture build alike. Hugo reads every
# environment variable whose name starts with HUGO, with any delimiter
# after the prefix, as config, so the build refuses every such name except
# this repo's four tool variables (the allowed list of sitecheck guard). It
# reads what a child process gets (env -0), which also holds names bash
# cannot declare (review3 A2). The self-test pins this whole function
# (wiring/hugo-build-pinned).
hugo_build() {
  local entry name
  while IFS= read -r -d '' entry; do
    name="${entry%%=*}"
    case "$name" in
      HUGO_BIN | HUGO_VERSION | HUGO_URL | HUGO_SHA256) ;;
      HUGO*)
        echo "hugo_build: the environment holds $name, which Hugo reads as config; only HUGO_BIN, HUGO_VERSION, HUGO_URL and HUGO_SHA256 may be set" >&2
        return 1
        ;;
    esac
  done < <(env -0)
  if [[ ! -x "$HUGO_BIN" ]]; then
    echo "hugo not found at $HUGO_BIN; run tools/fetch-tools.sh" >&2
    return 1
  fi
  "$HUGO_BIN" --source "$1" --gc --minify --panicOnWarning \
    --cleanDestinationDir --destination "$2"
}

step_build() { hugo_build "$CHECK_ROOT" "$CHECK_ROOT/public"; }

# fixture_inputs <root>: every top-level entry of <root> (dot entries
# included) sits in exactly one of FIXTURE_COPY, FIXTURE_CONTENT and
# FIXTURE_SKIP, and no name sits in two; every entry of a FIXTURE_CONTENT
# directory is a *.md file (copied) or a record section of
# FIXTURE_RECORD_SECTIONS (replaced by the fixture records). Prints one FAIL
# line per finding, or the count of classified entries.
fixture_inputs() {
  local root="$1" name entry dir section n=0 m=0 rc=0 restore known
  local -A seen=()
  for name in "${FIXTURE_COPY[@]}" "${FIXTURE_CONTENT[@]}" "${FIXTURE_SKIP[@]}"; do
    if [[ -n "${seen[$name]:-}" ]]; then
      echo "FAIL: fixture build: '$name' classified twice; keep it in exactly one of FIXTURE_COPY, FIXTURE_CONTENT and FIXTURE_SKIP in tools/check.sh" >&2
      rc=1
    fi
    seen[$name]=1
  done
  restore="$(shopt -p dotglob nullglob)"
  shopt -s dotglob nullglob
  for entry in "$root"/*; do
    name="${entry##*/}"
    n=$((n + 1))
    [[ -n "${seen[$name]:-}" ]] && continue
    echo "FAIL: fixture build: unclassified top-level path '$name'; add it to FIXTURE_COPY, FIXTURE_CONTENT or FIXTURE_SKIP in tools/check.sh" >&2
    rc=1
  done
  for dir in "${FIXTURE_CONTENT[@]}"; do
    for entry in "$root/$dir"/*; do
      name="${entry##*/}"
      m=$((m + 1))
      [[ -f "$entry" && ! -L "$entry" && "$name" == *.md ]] && continue
      known=""
      for section in "${FIXTURE_RECORD_SECTIONS[@]}"; do
        [[ "$name" == "$section" && -d "$entry" && ! -L "$entry" ]] && known=1
      done
      [[ -n "$known" ]] && continue
      echo "FAIL: fixture build: unclassified content entry '$dir/$name'; the fixture build copies only the top-level *.md of $dir/ and takes the record sections (${FIXTURE_RECORD_SECTIONS[*]}) from the fixture records, so classify it in tools/check.sh" >&2
      rc=1
    done
  done
  eval "$restore"
  [[ $rc -eq 0 ]] && echo "fixture inputs: $n top-level entries classified; $m content entries"
  return $rc
}

# step_fixture_build: classify the inputs, then assemble .fixture-site/ from
# the FIXTURE_COPY entries that exist, the top-level *.md of FIXTURE_CONTENT
# and the fixture records, and build it into public-fixtures/. Both
# directories are removed first, so a failed build leaves no stale tree for
# the steps after it to pass on, and an unclassified input stops it before
# the build.
step_fixture_build() {
  rm -rf "$FIXTURE_SITE" "$FIXTURE_PUBLIC" || return 1
  fixture_inputs "$CHECK_ROOT" || return 1
  mkdir -p "$FIXTURE_SITE/content" || return 1
  local item dir
  for item in "${FIXTURE_COPY[@]}"; do
    [[ -e "$CHECK_ROOT/$item" ]] || continue
    cp -R "$CHECK_ROOT/$item" "$FIXTURE_SITE/" || return 1
  done
  for dir in "${FIXTURE_CONTENT[@]}"; do
    mkdir -p "$FIXTURE_SITE/$dir" || return 1
    for item in "$CHECK_ROOT/$dir"/*.md; do
      [[ -e "$item" ]] || continue
      cp "$item" "$FIXTURE_SITE/$dir/" || return 1
    done
  done
  if [[ ! -d "$FIXTURE_RECORDS" ]]; then
    echo "fixture records not found at $FIXTURE_RECORDS" >&2
    return 1
  fi
  cp -R "$FIXTURE_RECORDS/." "$FIXTURE_SITE/content/" || return 1
  hugo_build "$FIXTURE_SITE" "$FIXTURE_PUBLIC"
}

# Both trees, the second even when the first fails.
step_html() {
  local rc=0
  html_check "$CHECK_ROOT/public" || rc=1
  html_check "$FIXTURE_PUBLIC" || rc=1
  return $rc
}

step_reflow() {
  local rc=0
  reflow_check "$CHECK_ROOT/public" || rc=1
  reflow_check "$FIXTURE_PUBLIC" || rc=1
  return $rc
}

step_links() { links_check "$CHECK_ROOT/public" "$EXTERNAL"; }

step_links_fixtures() { links_check "$FIXTURE_PUBLIC"; }

step_selftest() { bash "$CHECK_ROOT/tools/selftest.sh"; }

# require_work_tree: the guard reads git (tracked and untracked files), and
# so do its self-test cases, so outside a git work tree (a git archive
# export) every guard result would be a phantom failure. Fail once, early,
# with one message instead.
require_work_tree() {
  if ! git -C "$CHECK_ROOT" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    echo "FAIL: check.sh needs a git work tree (guard reads git): $CHECK_ROOT is not inside one" >&2
    return 1
  fi
}

check_main() {
  EXTERNAL=""
  case "${1:-}" in
    "") ;;
    --external) EXTERNAL=--external ;;
    *)
      echo "usage: bash tools/check.sh [--external]" >&2
      return 2
      ;;
  esac
  if [[ $# -gt 1 ]]; then
    echo "usage: bash tools/check.sh [--external]" >&2
    return 2
  fi

  cd "$CHECK_ROOT" || return 1
  require_work_tree || return 1
  if ! load_pins; then
    echo "FAIL: tools/pins.env could not be read" >&2
    return 1
  fi

  run_step fetch-tools step_fetch

  echo
  echo "==> shellcheck"
  step_shellcheck
  case $? in
    0) record shellcheck PASS ;;
    2) record shellcheck SKIPPED ;;
    *) echo "==> shellcheck: FAIL"; record shellcheck FAIL ;;
  esac

  run_step "guard (repo rules)" step_guard
  run_step "records (schema, defang)" step_records
  run_step "tokens (contrast, colour literals)" step_tokens
  run_step "literals (fixed copy only from data/labels.toml)" step_literals
  run_step build step_build
  run_step "site (third-party, CSP, defang)" step_site
  run_step "render (D6, D7, D10, structured data)" step_render
  run_step "fixture build" step_fixture_build
  run_step "site (fixture build)" step_site_fixtures
  run_step "render (fixture build)" step_render_fixtures

  if in_github_actions; then
    run_step "reflow (320 CSS px, both trees)" step_reflow
  else
    echo
    echo "==> reflow (320 CSS px, both trees)"
    echo "$REFLOW_NOT_RUN_LINE"
    record "reflow (320 CSS px, both trees)" "NOT RUN (CI only)"
  fi

  if in_github_actions; then
    run_step "html (Nu Html Checker, both trees)" step_html
  else
    echo
    echo "==> html (Nu Html Checker, both trees)"
    echo "$HTML_NOT_RUN_LINE"
    record "html (Nu Html Checker, both trees)" "NOT RUN (CI only)"
  fi

  if [[ -n "$EXTERNAL" ]]; then
    run_step "links (online, external included)" step_links
  else
    run_step "links (offline, internal)" step_links
  fi
  run_step "links (fixture build, offline)" step_links_fixtures

  if in_github_actions; then
    run_step selftest step_selftest
  else
    echo
    echo "==> selftest"
    if step_selftest; then
      record selftest "PASS (html and reflow fixtures NOT RUN, CI only)"
    else
      echo "==> selftest: FAIL"
      record selftest FAIL
    fi
  fi

  local i failed_steps=() skipped_steps=() not_run=0
  echo
  echo "==> Summary"
  for i in "${!STEP_NAMES[@]}"; do
    printf '  %-38s %s\n' "${STEP_NAMES[$i]}" "${STEP_RESULTS[$i]}"
    case "${STEP_RESULTS[$i]}" in
      FAIL) failed_steps+=("${STEP_NAMES[$i]}") ;;
      SKIPPED) skipped_steps+=("${STEP_NAMES[$i]}") ;;
      "NOT RUN"*) not_run=1 ;;
    esac
  done
  echo
  if [[ ${#failed_steps[@]} -gt 0 ]]; then
    echo "FAIL: ${#failed_steps[@]} step(s) failed: ${failed_steps[*]}"
    return 1
  fi
  local line
  if [[ $not_run -eq 1 ]]; then
    line="LOCAL PASS, HTML validation and reflow not run (CI only)"
  else
    line="PASS: every step ran and passed, HTML validation and reflow included"
  fi
  if [[ ${#skipped_steps[@]} -gt 0 ]]; then
    line="$line; SKIPPED: ${skipped_steps[*]}"
  fi
  echo "$line"
  return 0
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  set -uo pipefail
  check_main "$@"
fi
