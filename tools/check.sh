STEP_NAMES=()
STEP_RESULTS=()

record() {
  STEP_NAMES+=("$1")
  STEP_RESULTS+=("$2")
}

# run_step <name> <command...>: run, record PASS or FAIL, never abort.
run_step() {
  local name="$1"
  shift
  echo
  echo "==> $name"
  if "$@"; then
    record "$name" PASS
  else
    echo "==> $name: FAIL"
    record "$name" FAIL
  fi
}

