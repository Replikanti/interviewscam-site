#!/usr/bin/env bash
# The single local and CI entry point: CI runs `bash tools/check.sh` verbatim.
#
# Every step runs even after an earlier one failed, then a summary prints
# PASS / FAIL / SKIPPED / NOT RUN (CI only) per step, and the exit code is 1
# if any step failed.
#
# The Nu Html Checker (ADR-0002 part 1) and the reflow check (ADR-0003
# part 6) run only in CI (GITHUB_ACTIONS=true). Outside CI each step prints a
# loud NOT RUN line and the final line never uses all-pass wording. In CI a
# missing container runtime, image or Chrome is FAIL.
#
# Usage: bash tools/check.sh [--external] [--records DIR]
#   --external  check links online (third-party sites included) instead of
#               the offline internal-link check (ADR-0002 part 7); the
#               fixture build's links stay offline, because its sources
#               and lookups are placeholders
#   --records DIR
#               records mode (ADR-0007 part 5): build the site from this
#               checkout, which must be a valid pin (a green check on
#               public main), and the records of the private records repo
#               checked out in DIR, and run every content check on it. The
#               machinery steps print NOT RUN (records mode): the pinned
#               commit's green check holds them. Both flags at most once,
#               in either order.
#
# The fixture build (ADR-0004 part 10): production content/ has no records
# until milestone 5, so the record templates would meet no check before
# then. A second build of the real templates on the canonical fixture
# records (tests/fixtures/records/pass-fixture-site/) goes into
# public-fixtures/ and gets the same site, render, reflow, HTML and offline
# link checks. It is assembled in .fixture-site/, never in content/, and the
# deploy artifact stays public/ alone. Its inputs are classified (the
# FIXTURE_* arrays below), so no input of the production build is missing
# from it.
#
# tools/selftest.sh sources this file for html_check, links_check,
# reflow_check and the sitecheck functions, so the self-test runs exactly the invocations the real
# steps run; check_main and the strict mode below apply only when the file is
# executed.

CHECK_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# The fixture build: its source tree, its output and the records it adds.
FIXTURE_SITE="$CHECK_ROOT/.fixture-site"
FIXTURE_PUBLIC="$CHECK_ROOT/public-fixtures"
FIXTURE_RECORDS="$CHECK_ROOT/tests/fixtures/records/pass-fixture-site/content"
# Every top-level entry of the repo root on disk is classified, because Hugo
# reads the disk, not git: an ignored i18n/ or a stray go.mod would change
# the production build and not the fixture build (ADR-0004 part 10,
# amended). fixture_inputs fails on an entry in no array or in two.
#   FIXTURE_COPY     Hugo site inputs, copied whole into .fixture-site/ when
#                    present
#   FIXTURE_CONTENT  content: its top-level *.md are copied, and the record
#                    sections (FIXTURE_RECORD_SECTIONS) come from the fixture
#                    records; any other entry of content/ (a directory, a
#                    file that is not *.md) fails, because the fixture build
#                    would silently lack it
#   FIXTURE_SKIP     not read by the Hugo build, or generated by it or by
#                    this script
FIXTURE_COPY=(hugo.toml layouts assets data static i18n archetypes)
FIXTURE_CONTENT=(content)
FIXTURE_RECORD_SECTIONS=(reports campaigns)
FIXTURE_SKIP=(.git .github .gitignore .hugo_build.lock .tools .fixture-site
  .records-site public public-fixtures resources worktrees CLAUDE.md README.md
  docs lychee.toml schema tests tools worker)
# Records mode (ADR-0007 part 5): the assembled source tree of the
# production build on the records of DIR. Like .fixture-site/ it is
# git-ignored and rebuilt on every run; the build goes into public/, so the
# deploy and Lighthouse artifacts keep their path. It holds the records
# repo's sources (the real retired_slugs among them), so every records-mode
# run removes it at its end (step_records_cleanup): no later step of the
# job, such as an artifact upload, can find it.
RECORDS_SITE="$CHECK_ROOT/.records-site"
RECORDS_NOT_RUN_LINE="NOT RUN (records mode): machinery only, held by the pinned commit's green check"
# shellcheck source=tools/fetch-tools.sh
source "$CHECK_ROOT/tools/fetch-tools.sh"

HTML_NOT_RUN_LINE='NOT RUN: HTML validation (Nu Html Checker) was NOT run locally. It runs only in CI (required check job). A local green does not mean the HTML is valid.'
REFLOW_NOT_RUN_LINE='NOT RUN: reflow at 320 CSS px (sitecheck reflow) was NOT run locally, and with it its hidden-state cases (the Copy button hidden without its script, the search results hidden until a query, the skip link shown and legible on keyboard focus, the honeypot of the intake forms without a box), the hit test and paint check of the pinned regions (the intake forms and the result sections of /not-sent/ among them), and case (8), the search typed and submitted on Home against the oracle. It runs only in CI, in the runner'"'"'s Google Chrome. A local green does not mean the pages reflow or hide and reveal as they should, or that the search answers.'

in_github_actions() { [[ "${GITHUB_ACTIONS:-}" == true ]]; }

# html_check <absolute dir>: validate every HTML and CSS file under dir with
# the pinned Nu Html Checker image. Only ever called in CI.
html_check() {
  local dir="$1"
  if ! command -v docker >/dev/null 2>&1; then
    echo "FAIL: docker not found; in CI the Nu Html Checker must run" >&2
    return 1
  fi
  if ! docker image inspect "$VNU_IMAGE" >/dev/null 2>&1; then
    echo "FAIL: pinned Nu Html Checker image not present: $VNU_IMAGE" >&2
    echo "FAIL: tools/fetch-tools.sh pulls it in CI; see its output" >&2
    return 1
  fi
  docker run --rm --network none -v "$dir:/site:ro" --entrypoint vnu \
    "$VNU_IMAGE" --skip-non-html --also-check-css /site
}

# links_check <absolute dir> [--external]: check links in the built tree.
# root_dir and the self-link remap depend on the absolute path, so they are
# passed here rather than in lychee.toml.
links_check() {
  local dir="$1" mode="${2:-}"
  local -a online=(--offline)
  [[ "$mode" == --external ]] && online=()
  if [[ ! -x "$LYCHEE_BIN" ]]; then
    echo "FAIL: lychee not found at $LYCHEE_BIN; run tools/fetch-tools.sh" >&2
    return 1
  fi
  "$LYCHEE_BIN" --config "$CHECK_ROOT/lychee.toml" "${online[@]}" \
    --root-dir "$dir" \
    --remap "^https://interviewscam\\.com/(.*)\$ file://$dir/\$1" \
    -- "$dir"
}

# reflow_check <absolute dir> [no-search]: load every HTML page under dir at
# 320 CSS px in the runner's Google Chrome (ADR-0003 part 6), and run the
# search of Home with queries from the tree's feed (case (8), ADR-0005 part
# 6). Only ever called in CI. no-search (the self-test's reflow fixtures
# without a search.txt only) leaves out case (8); both builds always run it.
reflow_check() {
  local chrome search=()
  chrome="$(command -v google-chrome || command -v google-chrome-stable)" || {
    echo "FAIL: Google Chrome not found; in CI the reflow check must run" >&2
    return 1
  }
  [[ "${2:-}" == no-search ]] && search=(--no-search)
  sitecheck reflow --chrome "$chrome" "${search[@]}" "$1"
}

# The Chrome warm-up (ADR-0003 part 6, amended for #26): a fresh runner VM
# reads the Chrome install cold from disk, and the job's first launch waited
# on that read (state D in folio_wait_bit_common in 15 of 15 probes). In CI,
# a background read of the install starts after fetch-tools and is joined
# right before the first reflow call. Best effort: no function here returns
# non-zero, none writes to the step's output while the reader runs, and no
# outcome reaches an exit code (the 75 s budget and the retry stay the
# backstop).

# warm_chrome_libs: `ldd` output on stdin; prints the absolute path of every
# `name => /path (0x...)` line. vdso, `not found`, the interpreter line and
# anything else print nothing.
warm_chrome_libs() {
  sed -n 's/^[[:space:]]*[^[:space:]][^[:space:]]* => \(\/[^[:space:]]*\) (0x[0-9a-f]*)$/\1/p'
  return 0
}

# warm_chrome_files <chrome path> <root>: the paths to read, NUL-separated.
# The resolved Chrome's directory when it lies below <root> (regular files
# only, one filesystem: symlinks are not followed and FIFOs or devices are
# never opened), else the resolved file alone; plus the shared libraries of
# the resolved file and of a `chrome` ELF beside it (Google's package starts
# Chrome through a wrapper script) that exist and are readable regular files.
warm_chrome_files() {
  local real dir root="${2:-/opt}" lib
  real="$(readlink -f -- "$1" 2>/dev/null)"
  [[ -n "$real" ]] || return 0
  dir="${real%/*}"
  if [[ "$dir/" == "${root%/}/"?* ]]; then
    find "$dir" -xdev -type f -readable -print0 2>/dev/null
  elif [[ -f "$real" && -r "$real" ]]; then
    printf '%s\0' "$real"
  fi
  command -v ldd >/dev/null 2>&1 || return 0
  while IFS= read -r lib; do
    [[ -f "$lib" && -r "$lib" ]] && printf '%s\0' "$lib"
  done < <({ ldd "$real"; [[ "$dir/chrome" != "$real" && -f "$dir/chrome" ]] && ldd "$dir/chrome"; } 2>/dev/null | warm_chrome_libs)
  return 0
}

# warm_chrome_read <chrome path> <root> <dir>: the reader. Lists the files
# into <dir>/list, writes their count to <dir>/count, reads them all and
# writes ONE line `<files> <bytes> <seconds>` to <dir>/result.
warm_chrome_read() {
  local t0 files bytes
  export LC_ALL=C
  t0="$EPOCHREALTIME"
  warm_chrome_files "$1" "$2" >"$3/list" 2>/dev/null
  files="$(tr -cd '\0' <"$3/list" | wc -c)"
  echo "$files" >"$3/count"
  bytes="$(xargs -0 -r cat -- <"$3/list" 2>/dev/null | wc -c)"
  awk -v f="$files" -v b="$bytes" -v t0="$t0" -v t1="$EPOCHREALTIME" \
    'BEGIN { printf "%d %d %.1f\n", f, b, t1 - t0 }' >"$3/result"
  return 0
}

WARM_CHROME_PID=""
WARM_CHROME_DIR=""

# warm_chrome_start: CI only. Starts the reader in its own session (so the
# join can stop it and everything it started) at nice 19, with no output.
warm_chrome_start() {
  local chrome
  in_github_actions || return 0
  chrome="$(command -v google-chrome || command -v google-chrome-stable)" || return 0
  WARM_CHROME_DIR="$(mktemp -d)" || { WARM_CHROME_DIR=""; return 0; }
  export -f warm_chrome_files warm_chrome_libs warm_chrome_read
  if command -v setsid >/dev/null 2>&1; then
    setsid nice -n 19 bash -c 'warm_chrome_read "$@"' _ \
      "$chrome" "${WARM_CHROME_ROOT:-/opt}" "$WARM_CHROME_DIR" </dev/null >/dev/null 2>&1 &
  else
    nice -n 19 bash -c 'warm_chrome_read "$@"' _ \
      "$chrome" "${WARM_CHROME_ROOT:-/opt}" "$WARM_CHROME_DIR" </dev/null >/dev/null 2>&1 &
  fi
  WARM_CHROME_PID=$!
  export -nf warm_chrome_files warm_chrome_libs warm_chrome_read
  return 0
}

# warm_chrome_finish: joins the reader for at most WARM_CHROME_WAIT seconds
# (default 20), stops it if it is still running, prints one line. A no-op
# without a start, and after the first call.
warm_chrome_finish() {
  local pid="$WARM_CHROME_PID" dir="$WARM_CHROME_DIR" wait_s="${WARM_CHROME_WAIT:-20}"
  local deadline files bytes secs
  [[ -n "$pid" ]] || return 0
  WARM_CHROME_PID=""
  WARM_CHROME_DIR=""
  deadline="$(awk -v n="$EPOCHREALTIME" -v w="$wait_s" 'BEGIN { printf "%.3f", n + w }')"
  while kill -0 "$pid" 2>/dev/null; do
    if awk -v n="$EPOCHREALTIME" -v d="$deadline" 'BEGIN { exit !(n >= d) }'; then
      kill -TERM -- "-$pid" "$pid" 2>/dev/null
      wait "$pid" 2>/dev/null
      read -r files 2>/dev/null <"$dir/count"
      echo "reflow warm-up: still reading after ${wait_s} s, stopped (${files:-0} files listed)"
      rm -rf "$dir"
      return 0
    fi
    sleep 0.1
  done
  wait "$pid" 2>/dev/null
  if read -r files bytes secs 2>/dev/null <"$dir/result"; then
    awk -v f="$files" -v b="$bytes" -v s="$secs" 'BEGIN {
      printf "reflow warm-up: read %d files, %.1f MiB in %.1f s before the first launch\n", f, b / 1048576, s }'
  else
    echo "reflow warm-up: the reader left no result"
  fi
  rm -rf "$dir"
  return 0
}

# The safety nets (tools/sitecheck.py, ADR-0002 parts 3, 4 and 6), run in
# Python's isolated mode. Each prints its counts and exits 1 on findings,
# 2 on a usage or internal error.
sitecheck() { python3 -I "$CHECK_ROOT/tools/sitecheck.py" "$@"; }

# guard_check <repo root>: no JavaScript package tooling in the build chain
# (D3; the guard keeps the tool names out of tools/), Hugo hardening keys in
# hugo.toml and in the effective config of the pinned Hugo, actions owned by
# actions/ and pinned to commit SHAs, Pages off until M6.
guard_check() { sitecheck guard --root "$1" --hugo "$HUGO_BIN"; }

# records_check <root> <schema dir>: schema, x-defang (D8), live forms (R2),
# the SPEC section 5 body rule and the record rules R4 to R15 (ADR-0004) for
# every record and _index.md under <root>/content.
records_check() { sitecheck records --root "$1" --schemas "$2"; }

# site_check <root> <schema dir> <built dir> [no-built-pins|preview-pixels]:
# third-party requests (D9), the CSP meta from <root>/hugo.toml, no live
# artifact in the build (R3), and the built stylesheet and scripts against
# their pins; the fourth argument turns those pins off, for the self-test's
# hand-made site fixtures only (the check steps never pass it,
# wiring/site-built-pins), or adds the pixel check of the link preview card
# images (site rule (o), ADR-0009 part 6), which only the fixture build
# runs (wiring/site-preview-pixels): its cost grows with the records, on the
# private repo's metered minutes, and the fixture build holds the worst
# cases of the same template, whose errorf guards hold every build. With it
# comes the comparison of the committed fixture copies of the cards with
# that build (--preview-copies, ADR-0009 part 7): the fixture build draws
# the site card and every fixture record's card.
site_check() {
  local pins=() pixels=()
  [[ "${4:-}" == no-built-pins ]] && pins=(--no-built-pins)
  [[ "${4:-}" == preview-pixels ]] \
    && pixels=(--preview-pixels --preview-copies "$CHECK_ROOT/tests/fixtures")
  sitecheck site --records "$1" --schemas "$2" "${pins[@]}" "${pixels[@]}" "$3"
}

# render_check <root> <schema dir> <built dir> [<fixtures dir>] [no-feed]
# [no-search] [no-report-pins] [no-intake]: the markup contract of the record pages (ADR-0004): one page
# per record and none without one, the fixed titles, the D6, D7 and D10
# wording, the campaign line and attribution, artifacts and external links,
# structured data, no hidden persona name anywhere, the index lists, the
# data feed /feed.json against its schema, the records and /data-feed/
# (rules 11 to 13), and the A to Z page /a-z/ with the Home search form
# (rule 15, ADR-0005). With a fixtures dir, no record may share its slug or
# name with a fixture record under <fixtures dir>/**/content/ (the
# fixture-leak check; production only). no-feed, no-search,
# no-report-pins and no-intake (the self-test's hand-made render fixtures
# only) leave out rules 11 to 13, rules 15 and 16, rule 17 (the exact trees
# of the report pages, M4 PR 4) and rule 18 (the intake forms, their result
# pages and the page URL bound, M5b PR 3); both builds always run them.
render_check() {
  local fixtures=() feed=() search=() pins=() intake=()
  [[ -n "${4:-}" ]] && fixtures=(--fixtures "$4")
  [[ "${5:-}" == no-feed ]] && feed=(--no-feed)
  [[ "${6:-}" == no-search ]] && search=(--no-search)
  [[ "${7:-}" == no-report-pins ]] && pins=(--no-report-pins)
  [[ "${8:-}" == no-intake ]] && intake=(--no-intake)
  sitecheck render --records "$1" --schemas "$2" "${fixtures[@]}" "${feed[@]}" \
    "${search[@]}" "${pins[@]}" "${intake[@]}" "$3"
}

