# step_records_cleanup: remove .records-site/, the assembled copy of the
# records repo's sources, after every records-mode run, pass or fail. The
# next step of a job uploads an artifact, and the guard pins its paths
# (RECORDS_WITH), but a run that leaves no copy behind holds even when a
# path is widened. The build in public/ stays: it is the artifact.
step_records_cleanup() {
  rm -rf "$RECORDS_SITE" || return 1
  if [[ -e "$RECORDS_SITE" || -L "$RECORDS_SITE" ]]; then
    echo "FAIL: records cleanup: $RECORDS_SITE is still there" >&2
    return 1
  fi
  echo "records cleanup: .records-site/ removed"
}

# not_run_machinery <name>: a machinery step of the public run, which
# records mode leaves to the pinned commit's green check.
not_run_machinery() {
  echo
  echo "==> $1"
  echo "$RECORDS_NOT_RUN_LINE"
  record "$1" "NOT RUN (records mode)"
}

# ci_only_step <name> <function>: run in CI, a loud NOT RUN line elsewhere.
ci_only_step() {
  if in_github_actions; then
    run_step "$1" "$2"
  else
    echo
    echo "==> $1"
    case "$2" in
      *reflow*) echo "$REFLOW_NOT_RUN_LINE" ;;
      *) echo "$HTML_NOT_RUN_LINE" ;;
    esac
    record "$1" "NOT RUN (CI only)"
  fi
}

# records_step <run_step|ci_only_step> <name> <function>: a content step of
# records mode. After a failed records-repo step it does not run (fail
# closed: nothing of the records repo is copied, built or checked), and it
# is recorded NOT RUN (records repo failed); the records-repo FAIL already
# fails the run.
records_step() {
  if [[ -n "$RECORDS_REPO_FAILED" ]]; then
    echo
    echo "==> $2"
    echo "NOT RUN: the records repo step failed, so nothing of the records repo is copied, built or checked"
    record "$2" "NOT RUN (records repo failed)"
  else
    "$@"
  fi
}

# check_records_main: records mode. The pin step comes first, and the job
# token is unset right after it, so no later step (Hugo, lychee, the
# checks) ever holds it (wiring/records-token-unset). A failed records-repo
# step stops every step that reads the records repo (records_step), and
# .records-site/ and public/ are removed, so no stale tree stays behind.
# The last step removes .records-site/ after every run (step_records_cleanup).
check_records_main() {
  local sha
  if ! sha="$(git -C "$CHECK_ROOT" rev-parse --verify 'HEAD^{commit}')"; then
    echo "FAIL: records mode: cannot read HEAD of $CHECK_ROOT" >&2
    return 1
  fi
  run_step "pin (green check on public main)" step_pin "$sha"
  unset GH_TOKEN GITHUB_TOKEN
  run_step fetch-tools step_fetch
  warm_chrome_start
  not_run_machinery shellcheck
  run_step "guard (repo rules)" step_guard
  not_run_machinery "worker (intake Worker and deploy tool)"
  RECORDS_REPO_FAILED=""
  run_step "records repo (layout, workflows)" step_records_repo "$sha"
  if [[ "${STEP_RESULTS[-1]}" != PASS ]]; then
    RECORDS_REPO_FAILED=1
    rm -rf "$RECORDS_SITE" "$CHECK_ROOT/public"
  fi
  records_step run_step "records assembly" step_records_assembly
  records_step run_step "records (schema, defang)" step_records_records
  not_run_machinery "tokens (contrast, colour literals)"
  not_run_machinery "literals (fixed copy only from data/labels.toml)"
  records_step run_step build step_records_build
  records_step run_step "site (third-party, CSP, defang)" step_records_site
  records_step run_step "render (D6, D7, D10, structured data)" step_records_render
  not_run_machinery "fixture build"
  not_run_machinery "site (fixture build)"
  not_run_machinery "render (fixture build)"
  records_step ci_only_step "reflow (320 CSS px, production tree)" step_records_reflow
  records_step ci_only_step "html (Nu Html Checker, production tree)" step_records_html
  if [[ -n "$EXTERNAL" ]]; then
    records_step run_step "links (online, external included)" step_links
  else
    records_step run_step "links (offline, internal)" step_links
  fi
  not_run_machinery "links (fixture build, offline)"
  not_run_machinery selftest
  run_step "records cleanup (.records-site/ removed)" step_records_cleanup
  check_summary records "${sha:0:12}"
}

# parse_check_args <args...>: set EXTERNAL and RECORDS_DIR (resolved with
# cd -P) or print the usage and return 2. RECORDS_DIR must not be this
# checkout or lie inside it (Hugo and the guard would read the records as
# part of the public tree); this checkout inside RECORDS_DIR is the local
# layout, a pin worktree in the records clone's ignored worktrees/.
parse_check_args() {
  EXTERNAL=""
  RECORDS_DIR=""
  local usage="usage: bash tools/check.sh [--external] [--records DIR]" seen_records="" root
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --external)
        if [[ -n "$EXTERNAL" ]]; then
          echo "$usage (--external given twice)" >&2
          return 2
        fi
        EXTERNAL=--external
        shift
        ;;
      --records)
        if [[ -n "$seen_records" ]]; then
          echo "$usage (--records given twice)" >&2
          return 2
        fi
        seen_records=1
        if [[ $# -lt 2 || -z "$2" ]]; then
          echo "$usage (--records needs a directory)" >&2
          return 2
        fi
        if [[ ! -d "$2" ]]; then
          echo "check.sh: --records $2 is not a directory" >&2
          return 2
        fi
        RECORDS_DIR="$(cd -P -- "$2" && pwd)" || return 2
        shift 2
        ;;
      *)
        echo "$usage" >&2
        return 2
        ;;
    esac
  done
  if [[ -n "$RECORDS_DIR" ]]; then
    root="$(cd -P -- "$CHECK_ROOT" && pwd)" || return 2
    if [[ "$RECORDS_DIR" == "$root" || "$RECORDS_DIR" == "$root"/* ]]; then
      echo "check.sh: --records $RECORDS_DIR is this checkout or lies inside it; give the records repo's own checkout" >&2
      return 2
    fi
  fi
  return 0
}

# require_work_tree: the guard reads git (tracked and untracked files), and
# so do its self-test cases, so outside a git work tree (a git archive
# export) every guard result would be a phantom failure. Fail once, early,
# with one message instead.
require_work_tree() {
  if ! git -C "$CHECK_ROOT" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    echo "FAIL: check.sh needs a git work tree (guard reads git): $CHECK_ROOT is not inside one" >&2
    return 1
  fi
}

check_main() {
  parse_check_args "$@" || return 2

  cd "$CHECK_ROOT" || return 1
  require_work_tree || return 1
  if ! load_pins; then
    echo "FAIL: tools/pins.env could not be read" >&2
    return 1
  fi

  if [[ -n "$RECORDS_DIR" ]]; then
    check_records_main
    return
  fi

  run_step fetch-tools step_fetch
  warm_chrome_start

  echo
  echo "==> shellcheck"
  step_shellcheck
  case $? in
    0) record shellcheck PASS ;;
    2) record shellcheck SKIPPED ;;
    *) echo "==> shellcheck: FAIL"; record shellcheck FAIL ;;
  esac

  run_step "guard (repo rules)" step_guard
  run_step "worker (intake Worker and deploy tool)" step_worker
  run_step "records (schema, defang)" step_records
  run_step "tokens (contrast, colour literals)" step_tokens
  run_step "literals (fixed copy only from data/labels.toml)" step_literals
  run_step build step_build
  run_step "site (third-party, CSP, defang)" step_site
  run_step "render (D6, D7, D10, structured data)" step_render
  run_step "fixture build" step_fixture_build
  run_step "site (fixture build)" step_site_fixtures
  run_step "render (fixture build)" step_render_fixtures

  if in_github_actions; then
    run_step "reflow (320 CSS px, both trees)" step_reflow
  else
    echo
    echo "==> reflow (320 CSS px, both trees)"
    echo "$REFLOW_NOT_RUN_LINE"
    record "reflow (320 CSS px, both trees)" "NOT RUN (CI only)"
  fi

  if in_github_actions; then
    run_step "html (Nu Html Checker, both trees)" step_html
  else
    echo
    echo "==> html (Nu Html Checker, both trees)"
    echo "$HTML_NOT_RUN_LINE"
    record "html (Nu Html Checker, both trees)" "NOT RUN (CI only)"
  fi

  if [[ -n "$EXTERNAL" ]]; then
    run_step "links (online, external included)" step_links
  else
    run_step "links (offline, internal)" step_links
  fi
  run_step "links (fixture build, offline)" step_links_fixtures

  if in_github_actions; then
    run_step selftest step_selftest
  else
    echo
    echo "==> selftest"
    if step_selftest; then
      record selftest "PASS (html and reflow fixtures NOT RUN, CI only)"
    else
      echo "==> selftest: FAIL"
      record selftest FAIL
    fi
  fi

  check_summary public
}

# check_summary <public|records> [<sha12>]: the step table and the final
# line. Records mode never prints the public all-pass wording: its machinery
# steps did not run here.
check_summary() {
  local i failed_steps=() skipped_steps=() not_run=0
  # Every run ends here, also when a records-repo step failed and the reflow
  # step never ran: the warm-up reader and its directory must not outlive
  # check.sh. Idempotent: a no-op after step_reflow joined it.
  warm_chrome_finish
  echo
  echo "==> Summary"
  for i in "${!STEP_NAMES[@]}"; do
    printf '  %-38s %s\n' "${STEP_NAMES[$i]}" "${STEP_RESULTS[$i]}"
    case "${STEP_RESULTS[$i]}" in
      FAIL) failed_steps+=("${STEP_NAMES[$i]}") ;;
      SKIPPED) skipped_steps+=("${STEP_NAMES[$i]}") ;;
      "NOT RUN (CI only)") not_run=1 ;;
    esac
  done
  echo
  if [[ ${#failed_steps[@]} -gt 0 ]]; then
    echo "FAIL: ${#failed_steps[@]} step(s) failed: ${failed_steps[*]}"
    return 1
  fi
  local line
  if [[ "$1" == records && $not_run -eq 1 ]]; then
    line="RECORDS LOCAL PASS on $2, HTML validation and reflow not run (CI only)"
  elif [[ "$1" == records ]]; then
    line="RECORDS PASS on $2: every content check ran and passed"
  elif [[ $not_run -eq 1 ]]; then
    line="LOCAL PASS, HTML validation and reflow not run (CI only)"
  else
    line="PASS: every step ran and passed, HTML validation and reflow included"
  fi
  if [[ ${#skipped_steps[@]} -gt 0 ]]; then
    line="$line; SKIPPED: ${skipped_steps[*]}"
  fi
  echo "$line"
  return 0
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  set -uo pipefail
  check_main "$@"
fi
